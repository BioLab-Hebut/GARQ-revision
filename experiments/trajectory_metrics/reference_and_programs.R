args <- commandArgs(trailingOnly=TRUE)
out <- normalizePath(args[1],mustWork=TRUE)
suppressPackageStartupMessages({library(Seurat);library(slingshot);library(UCell);library(anndata);library(jsonlite)})
cfg <- fromJSON(file.path(out,'analysis_plan.json'),simplifyVector=FALSE)
genes <- unlist(cfg$gene_panel)
signatures <- lapply(cfg$signatures,unlist)
canon <- function(x) {x<-as.character(x);x[x=='Tumor (Neuronal-like)']<-'Tumor Cells (Dedifferentiated)';x}
set.seed(42)
states <- unlist(cfg$states)
paths <- c(SingleCell=file.path(out,'single_three_states.h5ad'),sapply(cfg$methods,function(x)x$rna))
all_manifest <- list()
for (name in names(paths)) {
  cat('START',name,format(Sys.time()),'\n');flush.console()
  a <- read_h5ad(paths[[name]])
  counts <- t(a$X)
  meta <- as.data.frame(a$obs)
  dimnames(counts) <- list(as.character(a$var_names),as.character(a$obs_names))
  if(!identical(colnames(counts),rownames(meta)))stop('Expression and metadata cell IDs differ')
  meta$celltype <- canon(meta$celltype)
  obj <- CreateSeuratObject(counts=counts,meta.data=meta)
  keep <- rownames(obj@meta.data)[obj$celltype %in% states]
  obj <- subset(obj,cells=keep)
  rm(a,counts,meta);gc()
  obj <- NormalizeData(obj,normalization.method='LogNormalize',scale.factor=10000,verbose=FALSE)
  mat <- GetAssayData(obj,assay='RNA',layer='data')
  missing <- setdiff(c(genes,unique(unlist(signatures))),rownames(mat))
  if(length(missing))stop('Fixed feature missing: ',paste(missing,collapse=','))
  score <- ScoreSignatures_UCell(mat,features=signatures,maxRank=1500,ncores=1)
  if(!all(colnames(obj)%in%rownames(score)))stop('UCell cell identifiers do not align')
  score <- score[colnames(obj),,drop=FALSE]
  if(ncol(score)!=3)stop('Expected three UCell signatures')
  clean_names <- sub('_UCell$','',colnames(score))
  if(anyDuplicated(clean_names)||!setequal(clean_names,names(signatures)))stop('UCell signature identifiers do not align')
  score <- score[,match(names(signatures),clean_names),drop=FALSE]
  colnames(score) <- names(signatures)
  gene_frame <- as.data.frame(t(as.matrix(mat[genes,,drop=FALSE])),optional=TRUE)
  colnames(gene_frame) <- genes
  frame <- data.frame(cell=colnames(obj),celltype=as.character(obj$celltype),gene_frame,score,check.names=FALSE)
  if(!all(genes%in%names(frame)))stop('Gene names were changed in export')
  if(name=='SingleCell') {
    obj <- FindVariableFeatures(obj,selection.method='vst',nfeatures=2000,verbose=FALSE)
    obj <- ScaleData(obj,verbose=FALSE)
    obj <- RunPCA(obj,features=VariableFeatures(obj),npcs=30,seed.use=42,verbose=FALSE)
    obj <- RunUMAP(obj,dims=1:30,n.neighbors=30,min.dist=0.3,seed.use=42,verbose=FALSE)
    sce <- slingshot(Embeddings(obj,'umap'),clusterLabels=as.character(obj$celltype),start.clus='Tumor Epithelial',end.clus='Stressed Tumor (p53+)',stretch=0)
    times <- slingPseudotime(sce)
    if(ncol(times)<1||!all(frame$cell%in%rownames(times)))stop('Reference pseudotime IDs do not align')
    if(!identical(as.character(slingLineages(sce)[[1]]),states))stop('Reference first lineage is not the specified three-state chain')
    frame$pseudotime <- times[frame$cell,1]
    write.csv(frame[,c('cell','celltype','pseudotime')],file.path(out,'single_three_states_pseudotime.csv'),row.names=FALSE)
    saveRDS(sce,file.path(out,'single_three_states_slingshot.rds'))
    all_manifest[[name]] <- list(n=ncol(obj),states=as.list(table(obj$celltype)),lineages=slingLineages(sce),n_lineages=ncol(times),nonfinite=sum(!is.finite(frame$pseudotime)),seed=42)
  } else {
    p <- read.csv(cfg$methods[[name]]$pt,colClasses=c(cell='character'))
    p$celltype <- canon(p$celltype)
    idx <- match(frame$cell,p$cell)
    if(anyNA(idx))stop('Archived pseudotime misses metacell IDs in ',name)
    if(!all(frame$celltype==p$celltype[idx]))stop('Archived pseudotime state labels mismatch in ',name)
    frame$pseudotime <- p$pseudotime[idx]
    all_manifest[[name]] <- list(n=ncol(obj),states=as.list(table(obj$celltype)),nonfinite=sum(!is.finite(frame$pseudotime)),pseudotime_source=cfg$methods[[name]]$pt)
  }
  write.csv(frame,file.path(out,paste0('programs_',name,'.csv')),row.names=FALSE)
  cat('DONE',name,'\n');flush.console()
  rm(obj,mat,frame,score);gc()
}
all_manifest$versions <- as.list(sapply(c('Seurat','slingshot','UCell','anndata','jsonlite'),function(x)as.character(packageVersion(x))))
all_manifest$sessionInfo <- capture.output(sessionInfo())
write_json(all_manifest,file.path(out,'reference_and_programs_manifest.json'),pretty=TRUE,auto_unbox=TRUE)
writeLines('SUCCESS',file.path(out,'reference_and_programs_SUCCESS.txt'))
cat('ALL_SUCCESS\n')
